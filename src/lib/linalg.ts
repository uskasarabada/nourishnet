// Minimal dense linear algebra — enough for a 10-feature regression.
// Written by hand (no ML library) so every step of the model is inspectable.

export type Matrix = number[][];
export type Vector = number[];

export function zeros(n: number, m: number): Matrix {
  return Array.from({ length: n }, () => new Array(m).fill(0));
}

export function dot(a: Vector, b: Vector): number {
  let s = 0;
  for (let i = 0; i < a.length; i++) s += a[i] * b[i];
  return s;
}

export function matVec(A: Matrix, x: Vector): Vector {
  return A.map((row) => dot(row, x));
}

/** Inverts a square matrix with Gauss–Jordan elimination and partial pivoting. */
export function invert(M: Matrix): Matrix {
  const n = M.length;
  const A = M.map((row, i) => [...row, ...Array.from({ length: n }, (_, j) => (i === j ? 1 : 0))]);
  for (let col = 0; col < n; col++) {
    let pivot = col;
    for (let r = col + 1; r < n; r++) if (Math.abs(A[r][col]) > Math.abs(A[pivot][col])) pivot = r;
    if (Math.abs(A[pivot][col]) < 1e-12) throw new Error('Matrix is singular');
    [A[col], A[pivot]] = [A[pivot], A[col]];
    const p = A[col][col];
    for (let j = 0; j < 2 * n; j++) A[col][j] /= p;
    for (let r = 0; r < n; r++) {
      if (r === col) continue;
      const f = A[r][col];
      if (f === 0) continue;
      for (let j = 0; j < 2 * n; j++) A[r][j] -= f * A[col][j];
    }
  }
  return A.map((row) => row.slice(n));
}

export function median(xs: number[]): number {
  if (xs.length === 0) return NaN;
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

export function mean(xs: number[]): number {
  return xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : NaN;
}

export function variance(xs: number[]): number {
  if (xs.length < 2) return 0;
  const m = mean(xs);
  return xs.reduce((a, b) => a + (b - m) ** 2, 0) / (xs.length - 1);
}
